def _is_spawn_name(name: Any) -> bool:
    if not isinstance(name, str):
        return False
    suffix = name.rsplit("__", 1)[-1]
    return suffix in {"spawn_agent", "Agent"} or suffix.endswith(
        "multi_agent_v1.spawn_agent"
    ) or suffix.endswith("multi_agent_v1spawn_agent")


def _find_spawn_tool(tools: Any) -> dict[str, Any] | None:
    if not isinstance(tools, list):
        return None
    for item in tools:
        if not isinstance(item,dict): continue
        if _is_spawn_name(item.get("name")): return item
        if item.get("type")=="namespace":
            child=_find_spawn_tool(item.get("tools",[]))
            if child:
                return {**child,"_namespace":item.get("name")}
    return None


def _safe_schema(value: Any) -> Any:
    """Keep schema structure while dropping prose and arbitrary defaults."""
    if isinstance(value, dict):
        return {
            key: _safe_schema(child)
            for key, child in value.items()
            if key not in {"description", "title", "default", "examples"}
        }
    if isinstance(value, list):
        return [_safe_schema(item) for item in value]
    return value


def _tool_schemas(tools: Any) -> list[dict[str, Any]]:
    if not isinstance(tools, list):
        return []
    schemas = []
    for tool in tools:
        if not isinstance(tool, dict) or not isinstance(tool.get("name"), str):
            continue
        schema = {
            key: tool[key]
            for key in ("type", "name", "strict", "parameters")
            if key in tool
        }
        schemas.append(_safe_schema(schema))
    return schemas


def _spawn_arguments(tool: dict[str, Any]) -> dict[str, Any]:
    parameters = tool.get("parameters")
    if not isinstance(parameters, dict):
        parameters = {}
    properties = parameters.get("properties")
    properties = properties if isinstance(properties, dict) else {}
    required = parameters.get("required", [])
    required = required if isinstance(required, list) else []
    values: dict[str, Any] = {}

    for key, schema in properties.items():
        if key not in required and key not in {"message","model","reasoning_effort","fork_context","fork_turns","agent_type"}:
            continue
        if not isinstance(schema, dict):
            continue
        kind = schema.get("type")
        enum = schema.get("enum")
        if key in {"message", "task", "prompt"}:
            values[key] = SPAWN_MESSAGE
        elif key in {"model", "model_name"}:
            values[key] = OVERFLOW_MODEL
        elif key in {"reasoning_effort", "effort"}:
            values[key] = "max"
        elif key == "fork_context":
            values[key] = False
        elif key == "agent_type":
            values[key] = "default"
        elif key == "fork_turns":
            values[key] = "none"
        elif key in {"cwd", "working_directory"}:
            values[key] = str(Path.cwd())
        elif key in {"title", "name"}:
            values[key] = "native-smoke-child"
        elif isinstance(enum, list) and enum:
            values[key] = "max" if "max" in enum else enum[0]
        elif kind == "string":
            values[key] = "native smoke"
        elif kind == "boolean":
            values[key] = False
        elif kind == "integer" or kind == "number":
            values[key] = 1
        elif kind == "array":
            values[key] = []
        elif kind == "object":
            values[key] = {}

    for key in required:
        if key not in values:
            schema = properties.get(key, {})
            if isinstance(schema, dict) and schema.get("type") == "string":
                values[key] = SPAWN_MESSAGE
            elif isinstance(schema, dict) and schema.get("type") == "boolean":
                values[key] = False

    # These are the essential arguments for the intended smoke even if the
    # schema has no required list. Keep the child request explicitly on mock-b.
    values["message"] = SPAWN_MESSAGE
    values["model"] = OVERFLOW_MODEL
    values["reasoning_effort"] = "max"
    return values


def _response(response_id: str, output: list[dict[str, Any]]) -> dict[str, Any]:
    return {
        "id": response_id,
        "object": "response",
        "created_at": int(time.time()),
        "status": "completed",
        "model": "mock-local",
        "output": output,
        "parallel_tool_calls": False,
        "tool_choice": "auto",
        "usage": {"input_tokens": 1, "output_tokens": 1, "total_tokens": 2},
    }


def _sse_event(kind: str, data: dict[str, Any]) -> bytes:
    return f"event: {kind}\ndata: {json.dumps(data, separators=(',', ':'))}\n\n".encode()


class _MockResponsesHandler(BaseHTTPRequestHandler):
    server_version = "LocalCodexSmoke/1.0"
    protocol_version = "HTTP/1.1"

    def log_message(self, _format: str, *_args: Any) -> None:
        return

    def do_POST(self) -> None:  # noqa: N802
        try:
            length = int(self.headers.get("Content-Length", "0"))
            request = json.loads(self.rfile.read(length).decode("utf-8"))
        except (ValueError, UnicodeError, json.JSONDecodeError):
            self.send_error(400)
            return
        model = request.get("model") if isinstance(request, dict) else None
        tools = request.get("tools", []) if isinstance(request, dict) else []
        spawn_tool = _find_spawn_tool(tools)
        record = {
            "model": model,
            "request_keys":list(request.keys()) if isinstance(request,dict) else [],
            "tool_schemas": _tool_schemas(tools),
            "spawn_tool_schema": _safe_schema(spawn_tool) if spawn_tool else None,
        }
        state = self.server.smoke_state  # type: ignore[attr-defined]
        with state["lock"]:
            state["requests"].append(record)
            index = len(state["requests"])
        call_spawn = index == 1 and model == PARENT_MODEL and spawn_tool is not None
        if model == PRIMARY_MODEL:
            time.sleep(1.0)
        if call_spawn:
            with state["lock"]:
                state["spawn_call_name"] = spawn_tool.get("name")
                state["spawn_arguments_model"] = OVERFLOW_MODEL
            self._send_function_call(spawn_tool)
        else:
            if model == PARENT_MODEL and index > 1: time.sleep(1.5)
            self._send_text_response()

    def _send_payload(self, payload: bytes, content_type: str) -> None:
        self.send_response(200)
        self.send_header("Content-Type", content_type)
        self.send_header("Cache-Control", "no-cache")
        self.send_header("Connection", "close")
        self.send_header("Content-Length", str(len(payload)))
        self.end_headers()
        self.wfile.write(payload)
        self.wfile.flush()
        self.close_connection = True

    def _send_function_call(self, tool: dict[str, Any]) -> None:
        response_id = "resp_native_smoke"
        arguments = json.dumps(_spawn_arguments(tool), separators=(",", ":"))
        events = [_sse_event("response.created", {"type":"response.created","response":{"id":response_id,"status":"in_progress"}})]
        items = []
        for index in range(2):
            item_id = f"fc_native_smoke_{index}"
            item = {"id":item_id,"type":"function_call","status":"completed",
                    "call_id":f"call_native_smoke_{index}","name":tool["name"],"arguments":arguments}
            if tool.get("_namespace"): item["namespace"]=tool["_namespace"]
            items.append(item)
            events.extend([
                _sse_event("response.output_item.added",{"type":"response.output_item.added","output_index":index,"item":{**item,"status":"in_progress","arguments":""}}),
                _sse_event("response.function_call_arguments.delta",{"type":"response.function_call_arguments.delta","item_id":item_id,"output_index":index,"delta":arguments}),
                _sse_event("response.function_call_arguments.done",{"type":"response.function_call_arguments.done","item_id":item_id,"output_index":index,"arguments":arguments}),
                _sse_event("response.output_item.done",{"type":"response.output_item.done","output_index":index,"item":item}),
            ])
        events.append(_sse_event("response.completed",{"type":"response.completed","response":_response(response_id,items)}))
        self._send_payload(b"".join(events), "text/event-stream")

    def _send_text_response(self) -> None:
        response_id = f"resp_final_{uuid.uuid4().hex[:8]}"
        item_id = f"msg_{uuid.uuid4().hex[:8]}"
        item = {
            "id": item_id,
            "type": "message",
            "status": "completed",
            "role": "assistant",
            "content": [
                {"type": "output_text", "annotations": [], "text": "Native smoke complete."}
            ],
        }
        completed = _response(response_id, [item])
        events = [
            _sse_event(
                "response.created",
                {"type": "response.created", "response": {"id": response_id, "status": "in_progress"}},
            ),
            _sse_event(
                "response.output_item.added",
                {"type": "response.output_item.added", "output_index": 0, "item": {**item, "status": "in_progress", "content": []}},
            ),
            _sse_event(
                "response.content_part.added",
                {"type": "response.content_part.added", "item_id": item_id, "output_index": 0, "content_index": 0, "part": {"type": "output_text", "annotations": [], "text": ""}},
            ),
            _sse_event(
                "response.output_text.delta",
                {"type": "response.output_text.delta", "item_id": item_id, "output_index": 0, "content_index": 0, "delta": "Native smoke complete."},
            ),
            _sse_event(
                "response.output_text.done",
                {"type": "response.output_text.done", "item_id": item_id, "output_index": 0, "content_index": 0, "text": "Native smoke complete."},
            ),
            _sse_event(
                "response.content_part.done",
                {"type": "response.content_part.done", "item_id": item_id, "output_index": 0, "content_index": 0, "part": item["content"][0]},
            ),
            _sse_event(
                "response.output_item.done",
                {"type": "response.output_item.done", "output_index": 0, "item": item},
            ),
            _sse_event("response.completed", {"type": "response.completed", "response": completed}),
        ]
        self._send_payload(b"".join(events), "text/event-stream")


def _safe_stderr(stderr: bytes, prompt: str) -> str:
    value = stderr.decode("utf-8", errors="replace")
    value = value.replace(prompt, "<smoke-prompt>")
    value = re.sub(r"(?i)(authorization\s*[:=]\s*bearer\s+)\S+", r"\1<redacted>", value)
    value = re.sub(r"(?i)(api[_-]?key\s*[:=]\s*)\S+", r"\1<redacted>", value)
    return value[-2400:]


def _state_snapshot(home: Path) -> dict[str, Any]:
    database = home / "control-center" / "subagent-policy.sqlite"
    if not database.exists():
        return {"event_names": [], "allocations": []}
    with sqlite3.connect(database) as connection:
        event_names = [
            row[0]
            for row in connection.execute(
                "SELECT event_name FROM hook_events ORDER BY id"
            )
        ]
        allocations = [
            {
                "model": row[0],
                "provider": row[1],
                "effort": row[2],
                "slot": row[3],
                "status": row[4],
                "has_agent_id": bool(row[5]),
            }
            for row in connection.execute(
                "SELECT model, provider, effort, slot, status, agent_id "
                "FROM allocations ORDER BY id"
            )
        ]
    return {"event_names": event_names, "allocations": allocations}


def run_smoke(codex_cli: Path = CODEX_CLI) -> dict[str, Any]:
    WORK_ROOT.mkdir(parents=True, exist_ok=True)
    run_dir = WORK_ROOT / f"run-{time.strftime('%Y%m%d-%H%M%S')}-{uuid.uuid4().hex[:8]}"
    run_dir.mkdir(parents=True)
    home = run_dir / "FAKE Codex HOME"
    home.mkdir()
    state: dict[str, Any] = {"lock": threading.Lock(), "requests": []}
    server = ThreadingHTTPServer(("127.0.0.1", 0), _MockResponsesHandler)
    server.daemon_threads = True
    server.smoke_state = state  # type: ignore[attr-defined]
    port = int(server.server_address[1])
    command_info = _make_fake_home(home, run_dir, port)
    server_thread = threading.Thread(target=server.serve_forever, daemon=True)
    server_thread.start()
    command = [
        str(codex_cli),
        "exec",
        "--json",
        "--ephemeral",
        "--skip-git-repo-check",
        "--dangerously-bypass-hook-trust",
        "-s",
        "read-only",
        "-m",
        PARENT_MODEL,
        "-C",
        str(run_dir),
        "-",
    ]
    env = {key:os.environ[key] for key in
           ("SystemRoot","WINDIR","PATH","PATHEXT","COMSPEC","PROGRAMFILES","PROGRAMFILES(X86)")
           if key in os.environ}
    env.update(
        {
            "CODEX_HOME": str(home),
            "CODEX_DISABLE_TELEMETRY": "1",
            "DO_NOT_TRACK": "1",
            "OPENAI_API_KEY": "dummy-smoke-key",
            "APPDATA": str(home / "AppData" / "Roaming"),
            "LOCALAPPDATA": str(home / "AppData" / "Local"),
            "TEMP": str(run_dir),
            "TMP": str(run_dir),
            "NO_PROXY": "*",
            "no_proxy": "*",
        }
    )
    prompt = (
        f"Use spawn_agent exactly twice with message 'mock child', model '{OVERFLOW_MODEL}', "
        "and reasoning_effort 'max'. Wait for its result, then reply 'smoke complete'."
    )
    cli_result: subprocess.CompletedProcess[bytes] | None = None
    error_type: str | None = None
    try:
        cli_result = subprocess.run(
            command,
            input=prompt.encode("utf-8"),
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            env=env,
            timeout=55,
            check=False,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        error_type = type(exc).__name__
    finally:
        server.shutdown()
        server.server_close()
        server_thread.join(timeout=2)

    with state["lock"]:
        requests = copy.deepcopy(state["requests"])
    policy_state = _state_snapshot(home)
    hook_events = policy_state["event_names"]
    child_models = [event.get("model") for event in requests if event.get("model") == PRIMARY_MODEL]
    spawn_tool_schemas = [
        request["spawn_tool_schema"]
        for request in requests
        if request.get("spawn_tool_schema") is not None
    ]
    cli_exit = cli_result.returncode if cli_result is not None else None
    stdout_types: list[str] = []
    stdout_tool_names: list[str] = []
    if cli_result is not None:
        for line in cli_result.stdout.decode("utf-8", errors="replace").splitlines():
            try:
                item = json.loads(line)
            except json.JSONDecodeError:
                continue
            if not isinstance(item, dict):
                continue
            event_type = item.get("type")
            if isinstance(event_type, str):
                stdout_types.append(event_type)
            name = item.get("name")
            if isinstance(name, str) and _is_spawn_name(name):
                stdout_tool_names.append(name)
    rewritten = bool(
        "PreToolUse" in hook_events
        and state.get("spawn_arguments_model")==OVERFLOW_MODEL
        and any(a["model"]==PRIMARY_MODEL for a in policy_state["allocations"])
    )
    actual_child_model = PRIMARY_MODEL in child_models
    smoke_passed = bool(
        cli_exit == 0
        and rewritten
        and actual_child_model
        and OVERFLOW_MODEL in [r.get("model") for r in requests]
        and "SubagentStop" in hook_events
        and spawn_tool_schemas
    )
    result: dict[str, Any] = {
        "passed": smoke_passed,
        "catalog_model_count":len(_make_catalog()["models"]),
        "exact_aliases_beyond_first_five_work":actual_child_model and OVERFLOW_MODEL in [r.get("model") for r in requests],
        "paid_requests":0,
        "cli_version": subprocess.check_output([str(codex_cli),"--version"],text=True).strip(),
        "cli_exit_code": cli_exit,
        "cli_error_type": error_type,
        "codex_cli": str(codex_cli),
        "fake_home": str(home),
        "fake_home_contains_spaces": " " in str(home),
        "windows_command": command_info["windows_command"],
        "commandWindows_executed": bool(hook_events),
        "hook_tool_names": [state.get("spawn_call_name")],
        "native_policy_state": policy_state,
        "native_updated_input_rewrote_model": rewritten,
        "responses_request_models": [request.get("model") for request in requests],
        "child_request_used_mock_a": actual_child_model,
        "spawn_tool_schema": spawn_tool_schemas[0] if spawn_tool_schemas else None,
        "cli_json_event_types": stdout_types,
        "cli_spawn_tool_names": stdout_tool_names,
        "hook_events": hook_events,
        "responses_requests": requests,
        "cli_stderr_tail": _safe_stderr(cli_result.stderr, prompt) if cli_result else "",
    }
    _write_json(WORK_ROOT / "native-smoke-result.json", result)
    _write_json(run_dir / "result.json", result)
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--codex-cli", type=Path, default=CODEX_CLI)
    args = parser.parse_args(argv)
    result = run_smoke(args.codex_cli)
    print(json.dumps({k:v for k,v in result.items() if k not in {"responses_requests","spawn_tool_schema","cli_json_event_types"}}, ensure_ascii=False, indent=2))
    return 0 if result["passed"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
